"""Chained-priority benchmark (added 1 November 2026).

Purpose: test settled-winner selection on fresh cases in which priorities form chains,
designed after the order effect on C04 had been seen but generated by a fixed seed and
fixed acceptance rules that were written down (protocol.json) before any repair was run.

Each case has three to five sources in a total order S1 > S2 > ... The rules of one source
share one effect, and the effect alternates from one source to the next, so that a lower
rule can be overridden by a higher one, which is in turn overridden by a still higher one
(an exception to an exception). Conditions are boxes over two bounded integers x, y in
[0, 5] and, sometimes, a Boolean f (72 requests in all).

Target (independent of the repair code): for every request, the decision of the highest
source that has a rule applying to it, or NotApplicable when no rule applies. The
requirements are one must-Permit or must-Deny requirement for every request whose target
is Permit or Deny, as in the frozen challenge.

Acceptance rules for a generated case (fixed in the protocol):
  1. every rule applies to at least one request;
  2. there is a chain h > w > l of rules from three different sources with alternating
     effects that all apply to at least one common request;
  3. no rule is forced to retire, i.e. the closed form of Equation 4.10 leaves every rule
     nonempty, so a repair that never empties a rule can meet the target;
  4. the closed form gives exactly the target on every request (a consistency check of
     the generator, not of the repair code).

Each case is run with both pair-selection rules in 12 rule orders: highest source first,
lowest source first and 10 seeded random orders. Scoring uses the independent evaluator
in common.py over the complete request space. Distinct accepted outputs are then replayed
in OPA and, when exportable, in Balana.

Usage (from the package root, with Z3_LIBRARY, OPA and BALANA_CP set):
  python studies/chain_study.py prepare
  python studies/chain_study.py run [workers]
  python studies/chain_study.py replay
  python studies/chain_study.py summarize
"""
import collections
import copy
import itertools
import json
import multiprocessing as mp
import os
import random
import statistics
import subprocess
import sys
import time
import xml.etree.ElementTree as ET
from datetime import datetime, timezone

from common import (RESULTS, MAX_ITERATIONS, TIMEOUT_MS, read, save, sha, source_hashes, score, canonical_hash,
                    decide, ev, tool_paths)

OUT = RESULTS / 'chain_study'
SEED = 20261101          # fixed before generation and before any run
N_CASES = 20
N_RANDOM_ORDERS = 10
MODES = ('listed', 'settled')
ATTRS = {'x': {'type': 'int', 'min': 0, 'max': 5}, 'y': {'type': 'int', 'min': 0, 'max': 5}, 'f': {'type': 'bool'}}
REQUESTS = [{'x': x, 'y': y, 'f': f} for x in range(6) for y in range(6) for f in (False, True)]


def box(rng):
    a, b = sorted(rng.randint(0, 5) for _ in range(2))
    c, d = sorted(rng.randint(0, 5) for _ in range(2))
    args = [{'op': 'ge', 'attr': 'x', 'value': a}, {'op': 'le', 'attr': 'x', 'value': b},
            {'op': 'ge', 'attr': 'y', 'value': c}, {'op': 'le', 'attr': 'y', 'value': d}]
    if rng.random() < 0.3:
        args.append({'op': 'eq', 'attr': 'f', 'value': rng.random() < 0.5})
    return {'op': 'and', 'args': args}


def region(rule):
    return frozenset(i for i, r in enumerate(REQUESTS) if ev(rule['condition'], r))


def analyse(rules, rank):
    """Return (reason or None, target decisions, closed-form regions)."""
    D = {r['id']: region(r) for r in rules}
    if any(not D[k] for k in D):
        return 'EMPTY_RULE', None, None
    eff = {r['id']: r['effect'] for r in rules}
    src = {r['id']: r['source'] for r in rules}
    by_rank = sorted(rules, key=lambda r: rank[r['source']])
    chain = any(rank[src[h]] < rank[src[w]] < rank[src[l]] and eff[h] != eff[w] != eff[l]
                and D[h] & D[w] & D[l]
                for h, w, l in itertools.permutations(D, 3))
    if not chain:
        return 'NO_CHAIN', None, None
    final = {}
    for r in by_rank:                                     # Equation 4.10, highest sources first
        removed = set()
        for w in by_rank:
            if rank[w['source']] < rank[r['source']] and w['effect'] != r['effect']:
                removed |= final[w['id']]
        final[r['id']] = D[r['id']] - removed
    if any(not final[k] for k in final):
        return 'FORCED_RETIREMENT', None, None
    target = []
    for i in range(len(REQUESTS)):
        applying = [r for r in by_rank if i in D[r['id']]]
        target.append(applying[0]['effect'] if applying else 'NotApplicable')
    closed = []
    for i in range(len(REQUESTS)):
        effects = {eff[k] for k in final if i in final[k]}
        closed.append('Conflict' if len(effects) == 2 else (effects.pop() if effects else 'NotApplicable'))
    if closed != target:
        return 'CLOSED_FORM_DIFFERS_FROM_TARGET', None, None
    return None, target, final


def generate():
    rng = random.Random(SEED)
    cases, discards, attempts = {}, collections.Counter(), 0
    while len(cases) < N_CASES:
        attempts += 1
        n_src = rng.choice([3, 4, 5])
        sources = [f'S{i + 1}' for i in range(n_src)]
        rank = {s: i for i, s in enumerate(sources)}
        start = rng.choice(['Permit', 'Deny'])
        other = {'Permit': 'Deny', 'Deny': 'Permit'}
        rules = []
        for i, s in enumerate(sources):
            effect = start if i % 2 == 0 else other[start]
            for j in range(rng.choice([1, 2])):
                rules.append({'id': f'{s}_r{j + 1}', 'source': s, 'effect': effect, 'condition': box(rng)})
        reason, target, final = analyse(rules, rank)
        if reason:
            discards[reason] += 1
            continue
        cid = f'K{len(cases) + 1:02}'
        model = {'schema_version': 'cpm-1', 'attributes': ATTRS,
                 'sources': {s: {'kind': 'synthetic', 'citation': f'Generated chained-priority case {cid} (seed {SEED})',
                                 'mapping_status': 'synthetic structured source; no external interpretation'} for s in sources},
                 'rules': rules,
                 'precedence': [{'higher': a, 'lower': b, 'approval_id': f'chain-direction-{a}-over-{b}'}
                                for a, b in zip(sources, sources[1:])],
                 'invariants': [{'id': f'{cid}_request_{i}_must_{t}',
                                 'when': {'op': 'and', 'args': [{'op': 'eq', 'attr': k, 'value': v} for k, v in REQUESTS[i].items()]},
                                 'required': t} for i, t in enumerate(target) if t != 'NotApplicable']}
        truth = [{'request': r, 'original_union_decision': decide(model, r), 'expected_final_decision': t,
                  'required': [t] if t != 'NotApplicable' else []} for r, t in zip(REQUESTS, target)]
        choices = [{'winner': w['id'], 'loser': l['id']} for w in rules for l in rules
                   if rank[w['source']] < rank[l['source']] and w['effect'] != l['effect']]
        cases[cid] = {'model': model, 'truth': truth, 'choices': choices, 'sources': len(sources), 'rules': len(rules),
                      'conflicting_pairs': sum(1 for c in choices
                                               if region(next(r for r in rules if r['id'] == c['winner']))
                                               & region(next(r for r in rules if r['id'] == c['loser']))),
                      'shadowed_losers': sorted(l['id'] for l in rules
                                                if region(l) <= set().union(*[region(w) for w in rules
                                                                              if rank[w['source']] < rank[l['source']]
                                                                              and w['effect'] != l['effect']] or [set()]))}
    return cases, discards, attempts


def orders(case_id, model):
    ids = [r['id'] for r in model['rules']]
    rank = {r['id']: int(r['source'][1:]) for r in model['rules']}
    out = {'highest_first': sorted(ids, key=lambda i: (rank[i], i)),
           'lowest_first': sorted(ids, key=lambda i: (-rank[i], i))}
    for k in range(N_RANDOM_ORDERS):
        perm = ids[:]
        random.Random(f'{SEED}:{case_id}:{k}').shuffle(perm)
        out[f'random_{k}'] = perm
    return out


def prepare():
    if (OUT / 'protocol.json').exists():
        raise SystemExit('Protocol already written; delete results/chain_study to start again.')
    cases, discards, attempts = generate()
    for cid, c in cases.items():
        save(OUT / 'cases' / cid / 'input.json', c['model'])
        save(OUT / 'cases' / cid / 'expected_truth_table.json', c['truth'])
        save(OUT / 'cases' / cid / 'authorized_choices.json', c['choices'])
    save(OUT / 'protocol.json', {
        'purpose': 'Does settled-winner selection accept fresh chained-priority cases in every rule order, and does the listed order?',
        'written_utc': datetime.now(timezone.utc).isoformat(timespec='seconds'),
        'seed': SEED, 'cases': N_CASES, 'generation_attempts': attempts, 'discarded': dict(discards),
        'acceptance_rules': ['every rule nonempty', 'a three-source alternating chain with a common request',
                             'no forced retirement (closed form leaves every rule nonempty)',
                             'closed form equals the independent target on every request'],
        'target': 'highest source with an applying rule decides; NotApplicable if none (independent of the repair code)',
        'requirements': 'one must-Permit or must-Deny requirement for every request whose target is Permit or Deny',
        'authorized_choices': 'every cross-source opposite-effect pair, winner from the higher source',
        'orders': ['highest_first', 'lowest_first'] + [f'random_{k}' for k in range(N_RANDOM_ORDERS)],
        'modes': {'listed': 'research.workflow.refine_bounded', 'settled': 'extensions.settled_refinement.refine_settled'},
        'max_iterations': MAX_ITERATIONS, 'timeout_ms': TIMEOUT_MS, 'requests_per_case': len(REQUESTS),
        'case_sha256': {cid: sha(OUT / 'cases' / cid / 'input.json') for cid in cases},
        'case_facts': {cid: {k: c[k] for k in ('sources', 'rules', 'conflicting_pairs', 'shadowed_losers')} for cid, c in cases.items()},
        'source_hashes': source_hashes(),
        'note': 'Designed on 1 November 2026, after the settled-winner rule and Proposition 4.6; '
                'the generator, seed and acceptance rules were fixed before any repair was run.'})
    print('cases', len(cases), 'attempts', attempts, 'discarded', dict(discards))


def job(args):
    cid, order_name, mode = args
    from pcproof.model import normalize, fingerprint
    from research import workflow
    from extensions.settled_refinement import refine_settled
    model = read(OUT / 'cases' / cid / 'input.json')
    truth = read(OUT / 'cases' / cid / 'expected_truth_table.json')
    choices = read(OUT / 'cases' / cid / 'authorized_choices.json')
    order = orders(cid, model)[order_name]
    pos = {k: i for i, k in enumerate(order)}
    rules = sorted(copy.deepcopy(model['rules']), key=lambda r: pos[r['id']])
    q = normalize({**copy.deepcopy(model), 'rules': rules})
    approval = {'approval_id': 'CHAIN_STUDY_' + cid, 'policy_sha256': fingerprint(q),
                'operation': 'bounded_refinement', 'choices': choices}
    run_ = workflow.refine_bounded if mode == 'listed' else refine_settled
    started = time.perf_counter()
    result = run_(q, approval, MAX_ITERATIONS, TIMEOUT_MS)
    elapsed = time.perf_counter() - started
    committed = bool(result.get('committed'))
    output = result['policy'] if committed else q
    row = {'case_id': cid, 'order': order_name, 'mode': mode, 'rule_order': order, 'status': result['status'],
           'reason': result.get('reason'), 'committed': committed, 'steps': len(result.get('iterations', [])),
           'output_canonical_sha256': canonical_hash(output) if committed else None,
           'elapsed_seconds_diagnostic': round(elapsed, 2)}
    row.update(score(output, truth))
    if committed:
        save(OUT / 'outputs' / cid / f"{mode}_{row['output_canonical_sha256'][:16]}.json", output)
    return row


def run(workers):
    protocol = read(OUT / 'protocol.json')
    assert protocol['source_hashes'] == source_hashes(), 'source changed after the protocol was written'
    for cid, h in protocol['case_sha256'].items():
        assert sha(OUT / 'cases' / cid / 'input.json') == h, 'case changed after the protocol was written'
    jobs = [(cid, o, m) for cid in protocol['case_sha256'] for o in protocol['orders'] for m in MODES]
    rows_path = OUT / 'rows.jsonl'
    done = set()
    if rows_path.exists():
        done = {(r['case_id'], r['order'], r['mode']) for r in map(json.loads, rows_path.read_text().splitlines())}
    jobs = [j for j in jobs if j not in done]
    with mp.Pool(workers) as pool, rows_path.open('a') as handle:
        for row in pool.imap_unordered(job, jobs):
            handle.write(json.dumps(row) + '\n')
            handle.flush()
            print(row['case_id'], row['order'], row['mode'], row['status'], row['reason'], row['steps'],
                  row['target_mismatches'], len(row['retired_rules']), row['elapsed_seconds_diagnostic'], flush=True)


def replay():
    from research import rego, xacml
    opa, cp = os.environ['OPA'], os.environ['BALANA_CP']
    summary = {'tools': tool_paths(), 'rows': {}}
    for path in sorted((OUT / 'outputs').glob('*/*.json')):
        cid, name = path.parent.name, path.stem
        model = read(path)
        truth = read(OUT / 'cases' / cid / 'expected_truth_table.json')
        requests = [r['request'] for r in truth]
        targets = [r['expected_final_decision'] for r in truth]
        expected = [decide(model, r) for r in requests]
        folder = OUT / 'replay' / cid / name
        folder.mkdir(parents=True, exist_ok=True)
        row = {'requests': len(requests)}
        conditions, wrapper, manifest = rego.generate(model)
        (folder / 'conditions.rego').write_text(conditions)
        (folder / 'decision.rego').write_text(wrapper)
        (folder / 'OPA_inputs.json').write_text(json.dumps({'cases': requests}))
        proc = subprocess.run([opa, 'eval', '--format=json', '--strict-builtin-errors',
                               '-d', str(folder / 'conditions.rego'), '-d', str(folder / 'decision.rego'),
                               '-d', str(folder / 'OPA_inputs.json'),
                               '[r | x := data.cases[_]; r := data.thesis.result with input as x]'],
                              capture_output=True, timeout=600)
        res = json.loads(proc.stdout)['result'][0]['expressions'][0]['value'] if proc.returncode == 0 else []
        row['opa_returncode'] = proc.returncode
        row['opa_model_mismatches'] = sum(a['decision'] != b for a, b in zip(res, expected)) + abs(len(res) - len(expected))
        row['opa_target_mismatches'] = sum(a['decision'] != t for a, t in zip(res, targets)) + abs(len(res) - len(targets))
        try:
            policy = folder / 'target.xml'
            attrs = xacml.export_cpm(model, policy)
            lines = []
            for i, r in enumerate(requests):
                req = folder / f'{i:03}.request.xml'
                xacml.request_xml(r, attrs, req)
                lines.append('\t'.join([str(i), str(policy), str(req), str(folder / f'{i:03}.response.xml')]))
            (folder / 'Balana_manifest.tsv').write_text('\n'.join(lines) + '\n')
            subprocess.run(['java', '-Xmx1024m', '-cp', cp, 'BalanaBatch', str(folder / 'Balana_manifest.tsv')],
                           capture_output=True, timeout=1200)
            bal = []
            for i in range(len(requests)):
                labels = [(n.text or '').strip() for n in ET.parse(folder / f'{i:03}.response.xml').getroot().iter()
                          if xacml.local(n) == 'Decision']
                bal.append(labels[0] if len(labels) == 1 else 'NO_SINGLE_DECISION')
            row['xacml_export'] = 'EXPORTED'
            row['balana_model_mismatches'] = sum(a != b for a, b in zip(bal, expected))
            row['balana_target_mismatches'] = sum(a != t for a, t in zip(bal, targets))
        except Exception as exc:
            row['xacml_export'] = 'REFUSED: ' + type(exc).__name__ + ': ' + str(exc)[:200]
        summary['rows'][f'{cid}/{name}'] = row
        print(cid, name, row, flush=True)
    save(OUT / 'replay_summary.json', summary)


def summarize():
    protocol = read(OUT / 'protocol.json')
    rows = [json.loads(l) for l in (OUT / 'rows.jsonl').read_text().splitlines()]
    n_orders = len(protocol['orders'])
    per_case = {}
    for cid in protocol['case_sha256']:
        per_case[cid] = {}
        for mode in MODES:
            sel = [r for r in rows if r['case_id'] == cid and r['mode'] == mode]
            assert len(sel) == n_orders, (cid, mode, len(sel))
            acc = [r for r in sel if r['committed']]
            per_case[cid][mode] = {
                'accepted_orders': len(acc), 'orders': len(sel),
                'accepted_with_any_failure': sum(1 for r in acc if r['target_mismatches'] or r['contract_violations']
                                                 or r['conflict_requests'] or r['retired_rules']),
                'distinct_accepted_outputs': len({r['output_canonical_sha256'] for r in acc}),
                'distinct_decision_signatures_accepted': len({r['decision_signature'] for r in acc}),
                'outcomes': dict(collections.Counter(f"{r['status']}/{r['reason']}" for r in sel)),
                'steps': sorted({r['steps'] for r in sel}),
                'highest_first': next(r['status'] for r in sel if r['order'] == 'highest_first'),
                'lowest_first': next(r['status'] for r in sel if r['order'] == 'lowest_first')}
    tot = {m: {'runs': sum(per_case[c][m]['orders'] for c in per_case),
               'accepted_runs': sum(per_case[c][m]['accepted_orders'] for c in per_case),
               'cases_accepted_in_every_order': sum(per_case[c][m]['accepted_orders'] == n_orders for c in per_case),
               'cases_accepted_in_some_but_not_all_orders': sum(0 < per_case[c][m]['accepted_orders'] < n_orders for c in per_case),
               'cases_never_accepted': sum(per_case[c][m]['accepted_orders'] == 0 for c in per_case),
               'accepted_with_any_failure': sum(per_case[c][m]['accepted_with_any_failure'] for c in per_case),
               'cases_with_one_accepted_output': sum(per_case[c][m]['distinct_accepted_outputs'] == 1 for c in per_case),
               'highest_first_accepted': sum(per_case[c][m]['highest_first'] == 'ACCEPTED' for c in per_case),
               'lowest_first_accepted': sum(per_case[c][m]['lowest_first'] == 'ACCEPTED' for c in per_case),
               'refusal_reasons': dict(collections.Counter(r['reason'] for r in rows if r['mode'] == m and not r['committed']))}
           for m in MODES}
    # The fields below were added on 1 November 2026, after the run; they only read rows.jsonl and the protocol.
    for m in MODES:
        acc_rows = [r for r in rows if r['mode'] == m and r['committed']]
        ref_rows = [r for r in rows if r['mode'] == m and not r['committed']]
        tot[m].update({
            'cases_with_a_refusal': sorted(c for c in per_case if per_case[c][m]['accepted_orders'] < n_orders),
            'accepted_orders_in_cases_with_a_refusal': {c: per_case[c][m]['accepted_orders'] for c in per_case
                                                        if per_case[c][m]['accepted_orders'] < n_orders},
            'attempted_edits_before_refusal': [min(r['steps'] for r in ref_rows), max(r['steps'] for r in ref_rows)] if ref_rows else None,
            'cases_whose_edit_count_varies_with_order': sorted(c for c in per_case if len(per_case[c][m]['steps']) > 1),
            'edits_per_accepted_run': [min(r['steps'] for r in acc_rows), max(r['steps'] for r in acc_rows)],
            'distinct_accepted_outputs_per_case': [min(per_case[c][m]['distinct_accepted_outputs'] for c in per_case),
                                                   max(per_case[c][m]['distinct_accepted_outputs'] for c in per_case)],
            'cases_whose_accepted_runs_differ_in_decisions': sum(per_case[c][m]['distinct_decision_signatures_accepted'] > 1 for c in per_case),
            'median_seconds_per_accepted_run_diagnostic': statistics.median(r['elapsed_seconds_diagnostic'] for r in acc_rows)})
    facts = protocol['case_facts']
    tot['cases_with_a_shadowed_loser'] = sorted(c for c, f in facts.items() if f['shadowed_losers'])
    tot['cases'] = {'n': len(per_case), 'sources': [min(f['sources'] for f in facts.values()), max(f['sources'] for f in facts.values())],
                    'rules': [min(f['rules'] for f in facts.values()), max(f['rules'] for f in facts.values())],
                    'conflicting_pairs': [min(f['conflicting_pairs'] for f in facts.values()), max(f['conflicting_pairs'] for f in facts.values())],
                    'cases_with_a_shadowed_loser': sum(1 for f in facts.values() if f['shadowed_losers']),
                    'generation_attempts': protocol['generation_attempts'], 'discarded': protocol['discarded']}
    if (OUT / 'replay_summary.json').exists():
        rep = read(OUT / 'replay_summary.json')['rows']
        tot['replay'] = {'outputs': len(rep),
                         'opa_model_mismatches': sum(r['opa_model_mismatches'] for r in rep.values()),
                         'opa_target_mismatches': sum(r['opa_target_mismatches'] for r in rep.values()),
                         'exported_to_xacml': sum(r['xacml_export'] == 'EXPORTED' for r in rep.values()),
                         'balana_model_mismatches': sum(r.get('balana_model_mismatches', 0) for r in rep.values()),
                         'balana_target_mismatches': sum(r.get('balana_target_mismatches', 0) for r in rep.values()),
                         'requests_per_output': 72}
    save(OUT / 'summary.json', {'totals': tot, 'cases': per_case})
    print(json.dumps(tot, indent=1))


if __name__ == '__main__':
    action = sys.argv[1]
    {'prepare': prepare, 'replay': replay, 'summarize': summarize}.get(action, lambda: run(int(sys.argv[2]) if len(sys.argv) > 2 else 2))()
